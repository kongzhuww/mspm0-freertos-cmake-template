// ==============================================================================
// 7-Pin SPI 模拟通信底层函数
// ==============================================================================
static void oled_write_byte(uint8_t dat, uint8_t cmd)
{
    if (cmd) {
        OLED_DC_SET(); // 写数据
    } else {
        OLED_DC_CLR(); // 写命令
    }

    OLED_CS_CLR(); // 拉低片选

    // 8位数据从高位至低位（MSB to LSB）模拟写入
    for (uint8_t i = 0; i < 8; i++) {
        OLED_SCL_CLR();
        if (dat & 0x80) {
            OLED_SDA_SET();
        } else {
            OLED_SDA_CLR();
        }
        OLED_SCL_SET();
        dat <<= 1;
    }

    OLED_SCL_CLR();
    OLED_CS_SET(); // 拉高片选
}

// ==============================================================================
// OLED 核心 API 实现
// ==============================================================================
void oled_init(void)
{
    // 复位 OLED 硬件
    OLED_RES_SET();
    OLED_DELAY_MS(100);
    OLED_RES_CLR();
    OLED_DELAY_MS(100);
    OLED_RES_SET();
    OLED_DELAY_MS(100);

    // SSD1306 配置命令序列
    oled_write_byte(0xAE, 0); // 关闭显示
    oled_write_byte(0xD5, 0); // 设置时钟分频因子/振荡器频率
    oled_write_byte(0x80, 0);
    oled_write_byte(0xA8, 0); // 设置路数
    oled_write_byte(0x3F, 0); // 1/64 duty
    oled_write_byte(0xD3, 0); // 设置显示偏移
    oled_write_byte(0x00, 0);
    oled_write_byte(0x40, 0); // 设置显示开始行
    oled_write_byte(0x8D, 0); // 电荷泵设置
    oled_write_byte(0x14, 0); // 开启电荷泵
    oled_write_byte(0x20, 0); // 内存寻址模式
    oled_write_byte(0x02, 0); // 页寻址模式
    oled_write_byte(0xA0, 0); // 段重映射 (0xA1左右翻转, 0xA0正常)
    oled_write_byte(0xC0, 0); // 行重映射 (0xC8上下翻转, 0xC0正常)
    oled_write_byte(0xDA, 0); // COM 硬件引脚配置
    oled_write_byte(0x12, 0);
    oled_write_byte(0x81, 0); // 对比度设置
    oled_write_byte(0xCF, 0);
    oled_write_byte(0xD9, 0); // 设置预充电周期
    oled_write_byte(0xF1, 0);
    oled_write_byte(0xDB, 0); // VCOMH 电平检测
    oled_write_byte(0x40, 0);
    oled_write_byte(0xA4, 0); // 全屏点亮/恢复常规 (0xA4常规, 0xA5全显)
    oled_write_byte(0xA6, 0); // 正常显示 (0xA6常规, 0xA7反显)
    oled_write_byte(0xAF, 0); // 开启显示

    oled_clear(); // 清屏
}

void oled_clear(void)
{
    // 清除 8 页共 1024 字节的内容
    for (uint8_t i = 0; i < 8; i++) {
        oled_write_byte(0xB0 + i, 0); // 设置页地址
        oled_write_byte(0x00, 0);     // 设置列低地址
        oled_write_byte(0x10, 0);     // 设置列高地址
        for (uint8_t j = 0; j < 128; j++) {
            oled_write_byte(0x00, 1); // 写入 0 清除像素
        }
    }
}

void oled_show_char(uint8_t x, uint8_t y, char chr, uint8_t size, uint8_t reverse)
{
    uint8_t c = chr - ' '; // 计算字库偏移
    if (x > 120 || y > 7) {
        return;
    }

    if (size == 16) {
        // 8x16 字符显示（占用 2 页高度）
        // 上半部分
        oled_write_byte(0xB0 + y, 0);
        oled_write_byte(((x & 0xF0) >> 4) | 0x10, 0);
        oled_write_byte((x & 0x0F), 0);
        for (uint8_t i = 0; i < 8; i++) {
            oled_write_byte(reverse ? ~oled_font_8x16[c][i] : oled_font_8x16[c][i], 1);
        }
        // 下半部分
        oled_write_byte(0xB0 + y + 1, 0);
        oled_write_byte(((x & 0xF0) >> 4) | 0x10, 0);
        oled_write_byte((x & 0x0F), 0);
        for (uint8_t i = 8; i < 16; i++) {
            oled_write_byte(reverse ? ~oled_font_8x16[c][i] : oled_font_8x16[c][i], 1);
        }
    }
}

void oled_show_string(uint8_t x, uint8_t y, const char *str, uint8_t size, uint8_t reverse)
{
    uint8_t w = (size == 16) ? 8 : 6;
    while (*str != '\0') {
        oled_show_char(x, y, *str, size, reverse);
        x += w; 
        if (x > 120) {
            x = 0;
            y += (size == 16) ? 2 : 1; 
        }
        str++;
    }
}

void oled_draw_cat_frame(const uint8_t frame_data[8][128], int16_t x_offset) {
    for (uint8_t page = 0; page < 8; page++) {
        oled_write_byte(0xB0 + page, 0);
        oled_write_byte(0x00, 0);
        oled_write_byte(0x10, 0);
        for (uint8_t col = 0; col < 128; col++) {
            int16_t img_col = col - x_offset;
            if (img_col >= 0 && img_col < 128) {
                oled_write_byte(frame_data[page][img_col], 1);
            } else {
                oled_write_byte(0x00, 1);
            }
        }
    }
}


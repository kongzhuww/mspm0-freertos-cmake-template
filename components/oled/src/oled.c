// ==============================================================================
// 7-Pin SPI 模拟通信底层函数
// ==============================================================================
static void oled_write_byte(uint8_t dat, uint8_t cmd)
{
    if (cmd) {
        OLED_DC_SET(); // 写数据
    } else {
        OLED_DC_CLR(); // 写命令
    }

    OLED_CS_CLR(); // 拉低片选

    // 8位数据从高位至低位（MSB to LSB）模拟写入
    for (uint8_t i = 0; i < 8; i++) {
        OLED_SCL_CLR();
        if (dat & 0x80) {
            OLED_SDA_SET();
        } else {
            OLED_SDA_CLR();
        }
        OLED_SCL_SET();
        dat <<= 1;
    }

    OLED_SCL_CLR();
    OLED_CS_SET(); // 拉高片选
}

// ==============================================================================
// OLED 核心 API 实现
// ==============================================================================

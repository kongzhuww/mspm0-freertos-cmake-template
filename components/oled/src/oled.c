// 延时宏：调度器运行前用 CPU 延时，运行后用 RTOS 挂起
#define OLED_DELAY_MS(ms)   do { \
    if (xTaskGetSchedulerState() != taskSCHEDULER_NOT_STARTED) { \
        vTaskDelay(pdMS_TO_TICKS(ms)); \
    } else { \
        delay_us((ms) * 1000); \
    } \
} while(0)

